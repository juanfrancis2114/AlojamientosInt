require('dotenv').config({quiet:true});
const { chromium, expect } = require('@playwright/test');
const fs = require('node:fs');
const base = process.argv[2];
if (!base || !/^https:\/\/[^/]+\.vercel\.app$/.test(base)) throw new Error('Indica una URL HTTPS de Vercel');
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const errors = [];
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(base + '/admin');
    await expect(page).toHaveURL(base + '/login', { timeout: 20000 });
    await expect(page.locator('#login-form')).toBeVisible();
    await page.goto(base);
    await expect.poll(() => page.locator('.hotel-card').count(), { timeout: 20000 }).toBeGreaterThanOrEqual(6);
    const hotels = await page.locator('.hotel-card').count();
    await expect.poll(()=>page.locator('.hotel-card img').evaluateAll(images=>images.slice(0,6).filter(img=>img.naturalWidth>0).length),{timeout:30000}).toBe(6);
    await page.evaluate(() => document.fonts.ready);
    fs.mkdirSync('artifacts', { recursive: true });
    await page.screenshot({ path: 'artifacts/cloud-react-desktop.png', fullPage: true });
    const resources = await page.evaluate(() => performance.getEntriesByType('resource').filter(entry => entry.name.includes('/assets/')).map(entry => ({ name: new URL(entry.name).pathname, durationMs: Math.round(entry.duration), transferBytes: entry.transferSize })));
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: 'artifacts/cloud-react-mobile.png', fullPage: true });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.getByRole('button', { name: 'Iniciar sesión' }).click();
    await expect(page.locator('#login-form')).toBeVisible();
    await page.locator('#close-modal').click();
    await page.setViewportSize({width:1440,height:1100});
    await page.locator('#account').click();
    await page.locator('#modal-content input[name=email]').fill(process.env.ADMIN_EMAIL);
    await page.locator('#modal-content input[name=password]').fill(process.env.ADMIN_PASSWORD);
    await page.locator('#modal-content #login-form .primary').click();
    await expect(page).toHaveURL(base+'/admin',{timeout:30000});
    await expect(page.getByRole('heading',{name:'Resumen ejecutivo'})).toBeVisible();
    await expect(page.locator('.erp-mini-stats')).toContainText('222');
    await expect(page.locator('.leaflet-container')).toBeVisible();
    await expect(page.locator('[data-view=orders]')).toHaveCount(0);
    await expect(page.getByText('Eventos de integración',{exact:true})).toHaveCount(0);
    await expect.poll(()=>page.locator('.leaflet-tile-loaded').count(),{timeout:15000}).toBeGreaterThan(0);
    await page.screenshot({path:'artifacts/cloud-erp-dashboard.png',fullPage:true});
    await page.locator('[data-tab=properties]').click();
    await expect(page.locator('#admin-content tbody tr')).toHaveCount(20);
    await page.locator('[aria-label="Buscar en alojamientos"]').fill('Sevilla Don Bosco');
    await expect(page.locator('#admin-content tbody tr')).toHaveCount(1);
    await page.screenshot({path:'artifacts/cloud-erp-alojamientos.png',fullPage:true});
    await page.locator('[data-tab=usuarios]').click();
    await expect(page.locator('#admin-content tbody')).toContainText(process.env.ADMIN_EMAIL);
    await page.locator('[data-tab=tarifas]').click();await expect(page.getByRole('heading',{name:'Calendario y tarifas'})).toBeVisible();
    await page.getByRole('button',{name:'+ Configurar período',exact:true}).click();await expect(page.locator('#calendar-form')).toBeVisible();await expect(page.locator('#calendar-form select option')).toHaveCount(270);await page.locator('#close-modal').click();
    await page.locator('[data-tab=facturas]').click();await expect(page.getByRole('heading',{name:'Facturas simuladas'})).toBeVisible();
    await page.locator('[data-tab=resenas]').click();await expect(page.getByRole('heading',{name:'Reseñas de estancias'})).toBeVisible();
    await page.getByRole('button',{name:'Mi perfil',exact:true}).click();await expect(page.locator('#profile-form')).toBeVisible();await page.goto(base+'/admin');await expect(page.getByRole('heading',{name:'Resumen ejecutivo'})).toBeVisible();
    await page.locator('[data-tab=dashboard]').click();
    await page.setViewportSize({width:390,height:844});
    await expect(page.locator('.leaflet-container')).toBeVisible();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    await page.screenshot({path:'artifacts/cloud-erp-mobile.png',fullPage:true});
    await page.locator('#account').click();
    await page.getByRole('button',{name:'Cerrar sesión'}).click();
    expect(errors).toEqual([]);
    fs.writeFileSync('artifacts/cloud-react-browser.json', JSON.stringify({ url: base, checkedAt: new Date().toISOString(), protectedRoute: true, hotels, mobileWidth: 390, overflow: false, pageErrors: errors, resources }, null, 2));
    console.log('React en nube verificado: ruta protegida, catálogo, login, CSS/JS, móvil sin desbordamiento ni errores de ejecución.');
  } catch (error) { if (errors.length) console.error('Errores de React:', JSON.stringify(errors)); throw error; }
  finally { await browser.close(); }
})().catch(error => { console.error(error.message); process.exitCode = 1; });
